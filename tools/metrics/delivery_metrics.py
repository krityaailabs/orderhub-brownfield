"""Delivery metrics from Git history and CI/CD exports (Section 12, Lab s12).

Four outcome measures, from three sources you already have:

  size            changed lines per merged pull request, excluding generated files     Git (numstat)
  review time     hours from opened to first review, and opened to merged                code host export
  change failure  share of deployments that failed (rolled back, hotfixed, incident)     CD export
  rework          share of merged pull requests followed within 21 days by a fix or      Git (Fixes-PR and
                  revert that names them                                                  Reverts-PR trailers)

Plus context that is easy to misread on its own: merged pull requests per week, lead time (opened to
deployed), and the deployment rework rate (unplanned deployments / all deployments; DORA's newer rework
measure).

Everything is reported per period (baseline before the rollout date, pilot after) and per cohort
(agent-assisted or not), and for the same people before and after. Small groups are marked.

Usage:
  python labs/s12/build_history.py /tmp/orderhub-history        # the lab's synthetic history
  python tools/metrics/delivery_metrics.py --repo /tmp/orderhub-history [--rollout 2026-04-06] [--out FILE]
"""

import csv
import fnmatch  # noqa: F401 - used once the Lab s12 measures are implemented
import statistics
import subprocess
import sys
import tempfile
from datetime import datetime, timedelta, timezone  # noqa: F401 - timedelta: Lab s12
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "labs" / "s12" / "data"
GENERATED = ("*.lock", "*/generated/*", "*.min.js", "*.snap")
REWORK_WINDOW_DAYS = 21
SMALL_GROUP = 20
SEP = "\x1f"


# ---------------------------------------------------------------- the four measures (Lab s12 tasks 1-4)

def changed_lines(files: list[tuple[int, int, str]]) -> int:
    """Changed lines (added + deleted) in a pull request, from Git numstat rows (added, deleted, path).
    Files matching any GENERATED pattern (fnmatch) don't count: a lock file regenerated by a dependency
    bump is not code anyone wrote or reviewed line by line. Binary files (numstat '-') arrive as -1, -1
    and don't count either."""
    raise NotImplementedError("Lab s12: implement changed_lines (Lecture 12.3)")


def review_hours(event: dict) -> tuple[float, float]:
    """(hours from opened to first review, hours from opened to merged), each rounded to 1 decimal place.
    Calendar hours, not working hours: say so wherever you show them. A pull request merged with no
    review has first_review_at == "" and counts its first-review wait as its merge time."""
    raise NotImplementedError("Lab s12: implement review_hours (Lecture 12.3)")


def change_failure_rate(deploys: list[dict]) -> float | None:
    """Failed deployments / all deployments, rounded to 3 places; None when there are no deployments.
    A deployment failed if its outcome is "failed". Count deployments, not pull requests: that's DORA's
    definition, and it's what users feel."""
    raise NotImplementedError("Lab s12: implement change_failure_rate (Lecture 12.3)")


def rework(prs: list[dict], data_end: datetime, all_prs: list[dict] | None = None,
           window_days: int = REWORK_WINDOW_DAYS) -> tuple[int, int]:
    """(reworked, eligible) for the pull requests in `prs`.

    A pull request is reworked if a LATER pull request names it in fixes or reverts and was merged within
    `window_days` of it. Fixes are looked for in `all_prs` (default: `prs`), because a fix can come from
    anyone and can land after the period you're summarising. A pull request is eligible only if a full
    window fits before data_end: one merged last week hasn't had 21 days to need a fix yet, and counting it
    would make recent work look better than it is (right-censoring). Fix and revert pull requests are
    eligible too."""
    raise NotImplementedError("Lab s12: implement rework (Lecture 12.3)")


# ---------------------------------------------------------------- loading

def _ts(text: str) -> datetime:
    return datetime.strptime(text, "%Y-%m-%dT%H:%M:%SZ").replace(tzinfo=timezone.utc)


def load_git(repo: Path) -> list[dict]:
    """One dict per squash-merged pull request: pr, author, agent, merged_at, fixes, reverts, files."""
    fmt = SEP.join(["@@%H", "%cI", "%(trailers:key=PR,valueonly,separator=%x2C)",
                    "%(trailers:key=Author,valueonly,separator=%x2C)",
                    "%(trailers:key=Agent-Assisted,valueonly,separator=%x2C)",
                    "%(trailers:key=Fixes-PR,valueonly,separator=%x2C)",
                    "%(trailers:key=Reverts-PR,valueonly,separator=%x2C)"])
    out = subprocess.run(["git", "-C", str(repo), "log", "--first-parent", "--numstat", f"--format={fmt}"],
                         capture_output=True, text=True, check=True).stdout
    prs = []
    for block in out.split("@@")[1:]:
        head, *rows = block.strip("\n").split("\n")
        _sha, when, pr, author, agent, fixes, reverts = (head.split(SEP) + [""] * 7)[:7]
        if not pr.strip():
            continue
        nums = lambda s: [int(x.strip().lstrip("#")) for x in s.split(",") if x.strip()]  # noqa: E731
        files = []
        for row in rows:
            if row.count("\t") >= 2:
                a, d, path = row.split("\t", 2)
                files.append((int(a) if a.isdigit() else -1, int(d) if d.isdigit() else -1, path))
        prs.append({"pr": nums(pr)[0], "author": author.strip(), "agent": agent.strip().lower() == "yes",
                    "merged_at": datetime.fromisoformat(when).astimezone(timezone.utc),
                    "fixes": nums(fixes), "reverts": nums(reverts), "files": files})
    return sorted(prs, key=lambda p: p["pr"])


def load_csv(path: Path) -> list[dict]:
    with path.open(newline="") as handle:
        return list(csv.DictReader(handle))


# ---------------------------------------------------------------- summarising

def _stats(values: list[float]) -> str:
    if not values:
        return "n/a"
    values = sorted(values)
    p90 = values[min(len(values) - 1, int(round(0.9 * (len(values) - 1))))]
    return f"{round(statistics.median(values), 1):g} / {round(p90, 1):g}"


def _pct(part: int, whole: int) -> str:
    return f"{100 * part / whole:.0f}% ({part}/{whole})" if whole else "n/a"


def group_row(name: str, prs: list[dict], events: dict[int, dict], weeks: float, data_end: datetime,
              all_prs: list[dict]) -> str:
    sizes = [changed_lines(p["files"]) for p in prs]
    times = [review_hours(events[p["pr"]]) for p in prs if p["pr"] in events]
    reworked, eligible = rework(prs, data_end, all_prs)
    flag = " ⚠ small" if len(prs) < SMALL_GROUP else ""
    over = sum(s > 300 for s in sizes)
    return (f"| {name}{flag} | {len(prs)} | {len(prs) / weeks:.1f} | {_stats(sizes)} | {_pct(over, len(sizes))} | "
            f"{_stats([t[0] for t in times])} | {_stats([t[1] for t in times])} | {_pct(reworked, eligible)} |")


def report(repo: Path, rollout: datetime, data: Path = DATA) -> str:
    prs = load_git(repo)
    events = {int(e["pr"]): e for e in load_csv(data / "pr_events.csv")}
    deploys = load_csv(data / "deploys.csv")
    for d in deploys:
        d["at"] = _ts(d["deployed_at"])
    start = min(p["merged_at"] for p in prs).replace(hour=0, minute=0, second=0)
    end = max(max(p["merged_at"] for p in prs), max(d["at"] for d in deploys))
    weeks = {"baseline": (rollout - start).days / 7, "pilot": (end - rollout).days / 7}
    base = [p for p in prs if p["merged_at"] < rollout]
    pilot = [p for p in prs if p["merged_at"] >= rollout]
    humans = lambda pp: [p for p in pp if not p["author"].endswith("-bot")]  # noqa: E731

    lines = [f"# Delivery metrics: baseline before {rollout:%Y-%m-%d}, pilot from {rollout:%Y-%m-%d}", "",
             f"Source: `{repo}` ({len(prs)} merged pull requests), `pr_events.csv`, `deploys.csv`. "
             f"Review times are calendar hours (median / p90). Size excludes generated files. Rework: fix or "
             f"revert within {REWORK_WINDOW_DAYS} days; pull requests merged in the last {REWORK_WINDOW_DAYS} "
             f"days are not yet eligible. Groups under {SMALL_GROUP} pull requests are marked ⚠ small.", "",
             "## Pull requests", "",
             "| Group | PRs | Per week | Size (median / p90) | Over 300 lines | First review h | Merge h | Rework |",
             "|---|---|---|---|---|---|---|---|"]
    rows = [("Baseline, all", base, "baseline"), ("Pilot, all", pilot, "pilot"),
            ("Pilot, agent-assisted (people)", [p for p in humans(pilot) if p["agent"]], "pilot"),
            ("Pilot, not agent-assisted", [p for p in pilot if not p["agent"]], "pilot"),
            ("Pilot, bot (dependency bumps)", [p for p in pilot if p["author"].endswith("-bot")], "pilot")]
    for name, group, period in rows:
        lines.append(group_row(name, group, events, weeks[period], end, prs))
    authors = {p["author"] for p in pilot if p["agent"] and not p["author"].endswith("-bot")}
    heavy = {a for a in authors
             if sum(p["agent"] for p in pilot if p["author"] == a) >= 0.5 * sum(p["author"] == a for p in pilot)}
    lines += ["", "## Same people, before and after", "",
              f"Heavy agent users in the pilot (half or more of their pull requests agent-assisted): "
              f"{', '.join(sorted(heavy)) or 'none'}. Compare each group with itself, not with the other group.", "",
              "| Group | PRs | Per week | Size (median / p90) | Over 300 lines | First review h | Merge h | Rework |",
              "|---|---|---|---|---|---|---|---|"]
    for label, members in (("Heavy users", heavy), ("Everyone else", {p["author"] for p in humans(prs)} - heavy)):
        for period, group in (("baseline", base), ("pilot", pilot)):
            mine = [p for p in group if p["author"] in members]
            lines.append(group_row(f"{label}, {period}", mine, events, weeks[period], end, prs))
    lines += ["", "## Deployments", "",
              "Lead time: opened to deployed, hours (median / p90), for pull requests shipped in the period.", "",
              "| Period | Deployments | Change failure rate | Unplanned (deployment rework) | Lead time h |",
              "|---|---|---|---|---|"]
    for period, ds in (("baseline", [d for d in deploys if d["at"] < rollout]),
                       ("pilot", [d for d in deploys if d["at"] >= rollout])):
        cfr = change_failure_rate(ds)
        unplanned = sum(d["kind"] == "unplanned" for d in ds)
        shown = "n/a" if cfr is None else f"{cfr:.0%}"
        lead = [(d["at"] - _ts(events[int(n)]["opened_at"])).total_seconds() / 3600
                for d in ds for n in d["prs"].split() if int(n) in events]
        lines.append(f"| {period} | {len(ds)} | {shown} | {_pct(unplanned, len(ds))} | {_stats(lead)} |")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    args = sys.argv[1:] if argv is None else argv
    default = Path(tempfile.gettempdir()) / "orderhub-history"
    repo = Path(args[args.index("--repo") + 1]) if "--repo" in args else default
    rollout = _ts((args[args.index("--rollout") + 1] if "--rollout" in args else "2026-04-06") + "T00:00:00Z")
    if not (repo / ".git").exists():
        print(f"no Git history at {repo}: run python labs/s12/build_history.py {repo}")
        return 2
    text = report(repo, rollout)
    if "--out" in args:
        Path(args[args.index("--out") + 1]).write_text(text)
    print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
